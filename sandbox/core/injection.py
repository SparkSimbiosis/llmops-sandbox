"""Детектор prompt injection на вході (W4, опційно): чотири родини патернів з уроку 8, українською й англійською.

1. Скасування інструкцій: «ignore previous instructions», «забудь / ігноруй інструкції».
2. Витяг системного промпта: «print / reveal your system prompt», «покажи свій системний промпт».
3. Підміна ролі: «you are now …», «act as …», «developer mode», «тепер ти …», «уяви, що ти …».
4. Соціальний тиск: «я твій розробник / адмін», прохання вимкнути перевірку чи обійти підтвердження.

Це не повний захист — лише перша лінія: mock розпізнає тільки канонічну англійську форму атаки,
а перефразовані варіанти ловимо тут, до роутера і до моделі. Збіг -> відмова без виклику моделі.

Хибна відмова теж дефект: клієнт, якого прийняли за атаку, лишається без відповіді. Тому
«скасування» — це дієслово і ціль поруч (до трьох слів між ними, без розділових знаків):
«ігноруй попередні інструкції». «Previous» / «попередн» самі ціллю не є: у «забудь моє попереднє
питання» людина забирає своє, а не правила бота. «Соціальний тиск» — заява про владу плюс команда:
згадка «ваш адміністратор порадив написати сюди» — звичайне звернення.
"""

import re

_NEAR = r"\s+(?:\w+\s+){0,3}"     # ціль — у межах трьох слів після дієслова, в тому самому реченні
_CLAIM_EN = r"\b(?:i am|i'm)\s+(?:your\s+)?(?:developer|admin|administrator|creator|owner)\b"
# «я твій / ваш розробник» — заява про себе; «ваш адмін дозволив / наказав» — посилання на чужу владу
_CLAIM_UA = (r"(?:\bя\s+(?:твій|ваш)\s+(?:розробник|адмін\w*|власник|творець)"
             r"|\b(?:твій|ваш)\s+(?:розробник|адмін\w*|власник|творець)\s+(?:дозволи|наказа|звели|розпоряди)\w*)")
_COMMAND = (r"(?:disable|bypass|skip|ignore|override|reveal|allowed|можна|дозволено|вимкн|обійд|обійти|пропуст|"
            r"зніми|зняти|ігнору|покажи|виведи|без\s+(?:підтвердж|перевірк|обмежен))")

_FAMILIES = {
    "override": [
        r"\b(ignore|disregard|forget|override)" + _NEAR + r"(instructions?|rules?|prompt|guidelines?)\b",
        r"(ігноруй\w*|ігнорувати|забудь\w*|не зважай\w*\s+на)" + _NEAR + r"(інструкц|правил|промпт)",
        r"(игнорируй\w*|забудь\w*)" + _NEAR + r"(инструкц|правил|промпт)",
    ],
    "exfiltrate": [
        r"\b(print|reveal|show|repeat|output)\b.{0,40}\bsystem\s*prompt",
        r"(покажи|виведи|повтори|роздрукуй).{0,40}(системн\w*\s+промпт|системн\w*\s+інструкц)",
        r"(покажи|выведи|повтори).{0,40}(системн\w*\s+промпт)",
    ],
    "role": [
        r"\byou are now\b", r"\bact as\b", r"\bdeveloper mode\b", r"\bjailbreak\b",
        r"(тепер ти|уяви, що ти|відтепер ти)",
    ],
    "social": [
        _CLAIM_EN + r".{0,80}" + _COMMAND,
        r"\b(disable|bypass|skip|turn off)\b.{0,30}\b(filter|restriction|check|approval|safety|rule)",
        _CLAIM_UA + r".{0,80}" + _COMMAND,
        r"(вимкни|обійди|зніми|пропусти)\W.{0,30}(обмежен|фільтр|перевірк|підтвердженн|правил)",
    ],
}
_COMPILED = [(fam, re.compile(p, re.I | re.S)) for fam, pats in _FAMILIES.items() for p in pats]

REFUSAL_TEXT = "Вибачте, не можу виконати це прохання."


def detect_injection(text: str) -> str | None:
    """Назва родини атаки або None."""
    for family, pattern in _COMPILED:
        if pattern.search(text):
            return family
    return None
